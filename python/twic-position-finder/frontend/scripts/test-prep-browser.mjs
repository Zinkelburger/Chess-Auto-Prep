import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import puppeteer from 'puppeteer-core';
import { serveDist } from './static-server.mjs';
const frontend = fileURLToPath(new URL('..', import.meta.url));
const root = path.resolve(frontend, '../../..');
const output = path.join(root, 'build/prep-web');
await fs.mkdir(output, { recursive: true });
// Served with public/_headers, as Cloudflare serves it: Stockfish must start under the bundled worker's isolation.
const { origin, close } = await serveDist(frontend);
// Chrome's singleton socket path must stay short; the job runner's TMPDIR is too long.
const chromeTmp = await fs.mkdtemp(path.join(os.homedir(), '.cache', 'ppt-'));
const browser = await puppeteer.launch({ executablePath: process.env.CHROME_BIN || '/usr/bin/google-chrome', headless: true, args: ['--disable-dev-shm-usage'], env: { ...process.env, TMPDIR: chromeTmp } });
try {
  const page = await browser.newPage(); page.setDefaultTimeout(30000);
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', dialog => dialog.accept());
  await page.setViewport({ width: 1440, height: 1100 });
  await page.setRequestInterception(true);
  page.on('request', req => req.url().startsWith(origin) || req.url().startsWith('data:') || req.url().startsWith('blob:') ? req.continue() : req.abort());
  const fill = async (selector, text) => page.$eval(selector, (el, value) => { el.value = value; el.dispatchEvent(new Event('input', { bubbles: true })); el.dispatchEvent(new Event('change', { bubbles: true })); }, text);
  const text = selector => page.$eval(selector, el => el.textContent);
  const board = () => page.$eval('#ch-board', el => el.getAttribute('aria-label'));
  const click = selector => page.$eval(selector, el => el.click());
  const noOverflow = async () => {
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('body *')].filter(e => e.getBoundingClientRect().right > innerWidth + 1).slice(0, 12).map(e => [e.tagName, e.id, e.className, e.getBoundingClientRect().right]))));
  };
  const importPgn = async pgn => { await fill('#ch-pgn', pgn); await click('#ch-pgn-import'); await page.waitForFunction(() => document.querySelector('#ch-pgn-import').disabled || document.querySelector('#ch-pgn-error').textContent); };
  const pgn = '[Event "Browser fixture"]\n[White "Alice"]\n[Black "Bob"]\n1.e4 {King pawn} e5 2.Nf3 (2.Bc4 Nc6) Nc6 *\n\n[Event "Second"]\n1.d4 d5 *';
  await page.goto(origin + '/pgn/');
  await page.waitForFunction(() => document.querySelector('#ch-engine-info').textContent.startsWith('Depth'), { timeout: 60000 });
  await importPgn(pgn);
  assert.equal(await page.$$eval('#px-games-list [data-game]', nodes => nodes.length), 2, 'both games are listed');
  assert.equal(await text('#px-game-count'), '1 / 2');
  await click('#px-games-list [data-game="0"]');
  assert.ok((await text('#ch-moves')).includes('Bc4'), 'variations are in the move list');
  assert.ok((await text('#ch-moves')).includes('King pawn'), 'comments are in the move list');
  const bc4 = await page.$$eval('#ch-moves [data-id]', nodes => nodes.find(n => n.textContent.includes('Bc4')).dataset.id);
  await click(`#ch-moves [data-id="${bc4}"]`);
  assert.match(await board(), /2B1P3/);
  // An engine line's move adds a variation, as on Lichess.
  await page.waitForSelector('.ch-pv-move');
  await click('.ch-pv-move');
  const accepted = await board();
  assert.notEqual(accepted, 'Chessboard: ' + 'rnbqkbnr/pppp1ppp/8/4p3/2B1P3/8/PPPP1PPP/RNBQK1NR b KQkq - 1 2');
  await new Promise(r => setTimeout(r, 800));
  await page.reload(); await page.waitForFunction(() => document.querySelector('#px-game-title').textContent.includes('Alice'));
  assert.equal(await board(), accepted, 'the game and the move shown come back after a reload');
  await importPgn('1. e9');
  assert.match(await text('#ch-pgn-error'), /No playable moves/);
  assert.equal(await board(), accepted, 'a bad import keeps the open games');
  const handoff = '7k/6pp/8/8/8/8/6PP/7K b - - 0 1';
  await page.goto(origin + '/pgn/?fen=' + encodeURIComponent(handoff));
  await page.waitForFunction(() => document.querySelector('#px-game-count').textContent === '3 / 3');
  assert.equal(new URL(page.url()).searchParams.has('fen'), false);
  assert.match(await board(), /7k\/6pp/);
  const session = await page.createCDPSession();
  await session.send('Browser.setDownloadBehavior', { behavior: 'allow', downloadPath: output });
  await fs.rm(path.join(output, 'games.pgn'), { force: true });
  await click('#ch-pgn-download');
  let exported;
  for (let i = 0; i < 100; i++) { try { exported = await fs.readFile(path.join(output, 'games.pgn'), 'utf8'); break; } catch { await new Promise(r => setTimeout(r, 50)); } }
  assert.ok(exported.includes('Bc4') && exported.includes('King pawn') && exported.includes('7k/6pp'), 'Download writes every game');
  await page.screenshot({ path: path.join(output, 'pgn-desktop.png') });
  await page.setViewport({ width: 390, height: 844 });
  await noOverflow();
  await page.screenshot({ path: path.join(output, 'pgn-mobile.png'), fullPage: true });
  await page.setViewport({ width: 1440, height: 1100 });
  console.log('PGN games, list, comments, variations, engine lines, reload, bad import, FEN handoff, download and phone layout passed.');

  await page.evaluate(() => localStorage.setItem('prep-expectimax-v1', JSON.stringify({ plies: 2, engineDepth: 6 })));
  await page.goto(origin + '/expectimax/');
  await page.waitForFunction(() => document.querySelector('#px-game-count').textContent === '3 / 3');
  assert.equal(await page.$eval('#px-expectimax', el => el.hidden), false, '/expectimax opens on its tab');
  assert.match(await text('.px-status'), /Not searched/);
  // The view redraws a moment after a press, so wait for the search to have shown and ended.
  const idle = () => page.waitForFunction(() => {
    const status = document.querySelector('.px-status').textContent;
    return document.querySelector('#px-run').textContent === 'Search' && !/^(Searching|Not searched)/.test(status);
  }, { timeout: 240000 });
  await click('#px-run'); await idle();
  assert.match(await text('.px-status'), /Maia 1600 · 2 of 2 plies/);
  const rows = await page.$$eval('button.px-row', rs => rs.map(r => [...r.children].map(c => c.textContent)));
  assert.ok(rows.length > 0, 'the table has moves');
  assert.ok(rows.some(r => r[2] && r[3]), 'a move holds both sides’ values');
  assert.ok(rows.some(r => r[1].endsWith('%')), 'Maia’s share is shown');
  await click('button.px-row');
  assert.match(await text('.px-status'), /1 ply from here/, 'following a searched move shows its subtree');
  await click('#ch-prev');
  await page.screenshot({ path: path.join(output, 'expectimax-desktop.png') });
  await page.setViewport({ width: 390, height: 844 });
  await noOverflow();
  await page.screenshot({ path: path.join(output, 'expectimax-mobile.png'), fullPage: true });
  await page.setViewport({ width: 1440, height: 1100 });
  await page.reload(); await page.waitForFunction(() => document.querySelectorAll('button.px-row').length > 0);
  assert.match(await text('.px-status'), /2 of 2 plies/, 'searches come back after a reload');
  // − and + step Rating by 100 and Depth by 1, within their limits; typing works too.
  await click('[aria-label="More rating"]');
  assert.equal(await page.$eval('#px-elo', el => el.value), '1700');
  await click('[aria-label="Less rating"]');
  assert.equal(await page.$eval('#px-elo', el => el.value), '1600');
  await fill('#px-plies', '9');
  assert.equal(await page.$eval('#px-plies', el => el.value), '8', 'Depth stops at its limit');
  assert.equal(await page.$eval('[aria-label="More depth"]', el => el.disabled), true);
  await click('[aria-label="Less depth"]');
  assert.equal(await page.$eval('#px-plies', el => el.value), '7');
  await fill('#px-plies', '6'); await click('#px-run');
  await page.waitForFunction(() => document.querySelector('.px-status').textContent.startsWith('Searching'));
  await click('#px-run');
  await page.waitForFunction(() => document.querySelector('.px-status').textContent.startsWith('Stopped'));
  assert.match(await text('.px-status'), /Stopped/);
  // The loaded Maia and Stockfish keep working without the connection.
  await page.setOfflineMode(true); await fill('#px-plies', '1'); await click('#px-run');
  await page.waitForFunction(() => /1 of 1 ply/.test(document.querySelector('.px-status').textContent), { timeout: 120000 });
  await page.setOfflineMode(false);
  console.log('Real Stockfish + Maia expectimax for both sides, table, following moves, reload, stop and offline search passed.');

  await page.goto(origin + '/tactics/');
  const local = path.join(output, 'tactics-fixture.pgn');
  await fs.writeFile(local, '[White "Alice"]\n[Black "Bob"]\n1. e4 e5 2. Qh5 Nc6 3. Qxe5+ Nxe5 *');
  await (await page.$('#tactics-pgn')).uploadFile(local);
  await page.waitForFunction(() => document.querySelector('#tactics-pgn-name').textContent.includes('tactics-fixture'));
  await page.$eval('details.advanced', el => el.open = true);
  await fill('#f-depth', '8'); await fill('#f-workers', '1'); await page.click('#btn-start');
  await page.waitForFunction(() => !document.querySelector('#view-train').hidden, { timeout: 120000 });
  await page.click('#btn-solution'); assert.equal(await page.$eval('#tr-line', el => el.hidden), false);
  assert.ok((await page.$eval('#tr-analyse-link', el => el.getAttribute('href'))).startsWith('/pgn/?fen='));
  await page.waitForFunction(() => document.querySelector('#tactics-save').textContent.includes('saved'));
  await page.screenshot({ path: path.join(output, 'tactics-desktop.png'), fullPage: true });
  await page.setViewport({ width: 390, height: 844 });
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('body *')].filter(e => e.getBoundingClientRect().right > innerWidth + 1).slice(0, 12).map(e => [e.tagName, e.id, e.className, e.getBoundingClientRect().right]))));
  await page.screenshot({ path: path.join(output, 'tactics-mobile.png'), fullPage: true });
  await page.reload(); await page.waitForFunction(() => !document.querySelector('#resume-tactics').hidden);
  await page.click('#resume-tactics'); assert.equal(await page.$eval('#view-train', el => el.hidden), false);
  console.log('PGN tactics mining with real Stockfish, solution, local viewer link and persisted training passed.');
  assert.deepEqual(errors, [], 'no browser exceptions');
  console.log(`Screenshots: ${output}`);
} finally { await browser.close(); close(); await fs.rm(chromeTmp, { recursive: true, force: true }); }
